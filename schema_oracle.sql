CREATE TABLE QUOTE (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_number      VARCHAR2(20) UNIQUE,
    designation VARCHAR2(200) NOT NULL,
    created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    sent_at     TIMESTAMP,
    status      VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
    customer_id NUMBER NOT NULL,
    CONSTRAINT fk_quote_customer FOREIGN KEY (customer_id) REFERENCES CUSTOMER(id),
    CONSTRAINT chk_quote_status CHECK (status IN ('DRAFT','SENT','ACCEPTED','REFUSED'))
);

CREATE TABLE QUOTE_ROW (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity   NUMBER(10,3) NOT NULL,
    quote_id   NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    CONSTRAINT fk_quoterow_quote   FOREIGN KEY (quote_id)   REFERENCES QUOTE(id) ON DELETE CASCADE,
    CONSTRAINT fk_quoterow_product FOREIGN KEY (product_id) REFERENCES PRODUCT(id),
    CONSTRAINT chk_quote_qty CHECK (quantity > 0)
);


